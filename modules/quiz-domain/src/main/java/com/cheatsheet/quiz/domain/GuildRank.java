package com.cheatsheet.quiz.domain;

import java.util.List;
import java.util.Optional;

/**
 * Ранг в гильдии — имя для накопленного уровня.
 *
 * <h2>Зачем имя, если уровень уже есть</h2>
 * Уровень отвечает на «сколько», ранг — на «кто я тут». Замер на живых итогах: единственное
 * место в продукте, где виден прогресс, — подпись под числом опыта, набранная 11px серым:
 * «Уровень 7 · до следующего 902 XP». Число 902 не отвечает ни на один вопрос — много это
 * или мало, близко или далеко: шкалы у него нет, а сам «уровень 7» ничего не говорит о том,
 * что было раньше и что будет дальше.
 *
 * <p>Ранг даёт шкале начало и конец: у ступени есть имя, у следующей ступени — тоже, и
 * расстояние между ними измеримо. Это не декоративная подпись: {@link #forLevel(int)} —
 * чистая функция от уровня, который сам выводится из XP ({@link UserExperience#levelForXp}),
 * то есть ранг остаётся честной агрегацией реальных попыток, а не выданной наградой.
 *
 * <h2>Почему именно ремесленная лестница</h2>
 * Продукт — мастерская гильдии, а не подземелье: ступени названы по цеховой иерархии
 * (ученик → подмастерье → ремесленник → мастер → старший мастер → хранитель → магистр),
 * без боевой лексики и без «эпических» степеней. Взрослый инструмент называет вещи так, как
 * их называют в ремесле.
 */
public enum GuildRank {

    /** Уровни 1–2: только пришёл, банк ещё незнакомый. */
    APPRENTICE("Ученик", 1),
    /** Уровни 3–5: работает под присмотром интервалов. */
    JOURNEYMAN("Подмастерье", 3),
    /** Уровни 6–9: своя рука набита, ошибки уже разбираются. */
    CRAFTSMAN("Ремесленник", 6),
    /** Уровни 10–14: держит несколько разделов целиком. */
    MASTER("Мастер", 10),
    /** Уровни 15–20: держит банк и знает его слабые места. */
    SENIOR_MASTER("Старший мастер", 15),
    /** Уровни 21–29: банк пройден, работа идёт на удержание. */
    KEEPER("Хранитель", 21),
    /** Уровень 30 и выше: дальше ступеней нет. */
    MAGISTER("Магистр", 30);

    private static final List<GuildRank> ALL = List.of(values());

    private final String title;
    private final int minLevel;

    GuildRank(String title, int minLevel) {
        this.title = title;
        this.minLevel = minLevel;
    }

    /** Название ступени — то, что человек видит. */
    public String title() {
        return title;
    }

    /** Уровень, с которого ступень начинается. */
    public int minLevel() {
        return minLevel;
    }

    /**
     * Ступень для уровня. Уровни ниже первого (некорректный ввод) считаются первым:
     * у прогрессии нет «отрицательного» состояния, а бросать исключение из-за подписи —
     * значит ронять страницу итогов на ровном месте.
     */
    public static GuildRank forLevel(int level) {
        GuildRank current = APPRENTICE;
        for (GuildRank rank : ALL) {
            if (level >= rank.minLevel) {
                current = rank;
            }
        }
        return current;
    }

    /** Следующая ступень, если она есть. У последней ступени продолжения нет — и это правда. */
    public Optional<GuildRank> next() {
        int index = ALL.indexOf(this);
        return index + 1 < ALL.size() ? Optional.of(ALL.get(index + 1)) : Optional.empty();
    }

    /** Все ступени в порядке возрастания — для витрины пути. */
    public static List<GuildRank> all() {
        return ALL;
    }
}
