/**
 * Свернуть на телефоне то, что смотрят изредка.
 *
 * Витрина знаков (766px) и форма отбора (345px) на 390×844 лежат между метриками и
 * темами: мимо них проходят каждый раз, а открывают редко. Тем же свойством обладает
 * план ответа на экране вопроса: без сворачивания он вместе с часами репетиции уводил
 * поле ввода на 920-й пиксель при сгибе 844 (замер 390×844, интервью). В разметке все
 * они стоят `<details open>` — без скрипта страница остаётся рабочей, просто длинной;
 * это и есть прогрессивное улучшение, а не зависимость.
 *
 * Модуль лежит в `ui/`, а не в `stats/`: страниц-жильцов стало две, и общий приём из
 * папки одной страницы читался бы как её частность.
 *
 * Закрываем ОДИН раз при загрузке и только если человек ещё не трогал раскрытие:
 * `toggle` снимает пометку, и повторный вызов (смена ориентации, resize) уже не
 * закрывает то, что открыли руками.
 */
/**
 * @param {string} query условие, при котором раскрытия закрываются. По умолчанию —
 *   телефон: на аналитике ограничение горизонтальное (блоки лежат в одной колонке
 *   на узком экране). Экран вопроса передаёт своё: там ограничение ВЕРТИКАЛЬНОЕ —
 *   план стоит над полем ввода, и в стопке (уже 1280) или в низком окне (ниже
 *   800) он уводит «Показать ответ» за сгиб. Замер до правки: действие на 1030 при
 *   сгибе 982 (1512×982) и на 1169 при 1024 (768×1024).
 */
export function initMobileDisclosures(query = '(max-width: 767px)') {
  const phone = window.matchMedia(query);
  const targets = [...document.querySelectorAll('details[data-mobile-collapsed]')];
  if (!targets.length) {
    return;
  }

  targets.forEach((details) => {
    details.addEventListener('toggle', () => {
      details.removeAttribute('data-mobile-collapsed');
    }, { once: true });
  });

  const apply = () => {
    if (!phone.matches) {
      return;
    }
    targets.forEach((details) => {
      if (details.hasAttribute('data-mobile-collapsed')) {
        details.open = false;
      }
    });
  };

  apply();
  phone.addEventListener('change', apply);
}
