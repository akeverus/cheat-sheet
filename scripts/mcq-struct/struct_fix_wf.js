export const meta = {
  name: 'mcq-struct-parity-fix',
  description: 'Выравнивание визуальной структуры дистракторов под correct (анти-телл)',
  phases: [{ title: 'StructFix', detail: 'по ~6 блоков на агента; переписываются ТОЛЬКО дистракторы' }],
}

const A = args
const SCHEMA = {
  type: 'object', required: ['blocks'],
  properties: {
    blocks: {
      type: 'array',
      items: {
        type: 'object', required: ['q_number', 'wrong_texts'],
        properties: {
          q_number: { type: 'integer' },
          wrong_texts: { type: 'array', items: { type: 'string' }, minItems: 3, maxItems: 3 },
        },
      },
    },
  },
}

function prompt(c) {
  return `Ты чинишь ВИЗУАЛЬНЫЙ АНТИ-ТЕЛЛ в MCQ по теме «${A.topic}».

ПРОБЛЕМА, которую ты устраняешь: правильный ответ отличается от неправильных не смыслом,
а ФОРМОЙ — он длиннее по символам, состоит из большего числа частей (запятых и тире) и чаще
содержит противопоставление. Читатель выбирает его не думая. Это провал независимо от смысла.

Читай Read инструментом \`${A.json_path}\` целиком и \`${A.md_path}\` с offset=${c.off}, limit=${c.lim}.
Твой диапазон — блоки Q${c.lo}..Q${c.hi}.

ЗАДАЧА: для каждого блока перепиши ТРИ НЕПРАВИЛЬНЫХ варианта так, чтобы они стали визуально
неотличимы от правильного. ПРАВИЛЬНЫЙ ВАРИАНТ НЕ ТРОГАЙ ВООБЩЕ.

ЧЕТЫРЕ ОСИ ПАРИТЕТА — считай их у correct и повторяй в каждом дистракторе:
1. ЧАСТИ ФРАЗЫ: посчитай у correct запятые, тире и точки с запятой. У дистрактора должно быть
   столько же (ровно). Если correct двухчастный «X делает A, а Y делает B» — дистрактор тоже
   двухчастный, а не одна короткая реплика.
2. ДЛИНА В СИМВОЛАХ: коридор 0.85–1.15 от длины correct. Примерно поровну чуть выше и чуть ниже —
   не делай все три длиннее.
3. КОД-СПАНЫ в обратных кавычках: столько же, сколько у correct (разница максимум один).
   Это критично: при равной длине опция без код-спанов содержит заметно больше обычных слов,
   и correct снова выделяется. Идентификаторы бери только из тела своего Q.
4. ПРОТИВОПОСТАВЛЕНИЕ («а», «тогда как», тире, «в отличие»): либо есть у всех четырёх, либо ни у кого.

ЗАПРЕЩЕНО (иначе правка хуже исходного):
- Копировать зачин correct. Все четыре строки начинаются ПО-РАЗНОМУ и не имеют общих кусков
  длиннее 4-5 слов подряд — иначе появятся повторяющиеся n-граммы.
- Приписывать верную преамбулу из correct к ложному хвосту: дистрактор ложен ЦЕЛИКОМ,
  а не «правильное начало + неверный конец».
- Скапливать в дистракторах отрицания («не», «без», «вместо») и абсолютистские обороты
  («только», «всегда», «никогда», «любой», «целиком», «лишь», «достаточно»), если их нет в correct.
- Раздувать текст канцеляритом ради символов.

СОХРАНИТЬ БЕЗ ИЗМЕНЕНИЙ:
- СМЫСЛ ошибки каждого дистрактора: он остаётся ложным ровно по той же оси и опровергается тем же
  местом тела Q. Ты меняешь ФОРМУ, а не суть заблуждения.
- Порядок: wrong_texts[i] соответствует i-му неправильному варианту в файле (A→D, пропуская correct).
- Лексику своего Q: никаких новых API, чисел, версий и терминов, которых нет в теле этого Q.
- Естественный русский; слова «якобы», «будто», «почему-то» запрещены.

Верни СТРОГО {"blocks":[{"q_number":N,"wrong_texts":["...","...","..."]}, ...]} для всех блоков
Q${c.lo}..Q${c.hi}. Ничего кроме структурированного ответа.`
}

phase('StructFix')
const res = await parallel(A.chunks.map(c => () =>
  agent(prompt(c), { label: `struct:${c.label}`, phase: 'StructFix', schema: SCHEMA })))

const blocks = res.filter(Boolean).flatMap(r => r.blocks || [])
log(`переписано блоков: ${blocks.length}`)
return { count: blocks.length, q_numbers: blocks.map(b => b.q_number).sort((a, b) => a - b),
         chunks_ok: res.filter(Boolean).length, chunks_total: A.chunks.length }
