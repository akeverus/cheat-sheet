export const meta = {
  name: 'mcq-struct-repair',
  description: 'Выравнивание структурного паритета вариантов без изменения смысла (раздел 99)',
  phases: [{ title: 'Repair', detail: 'агенты правят только тексты опций, смысл и correct не трогают' }],
}
const A = args
const SCHEMA = {
  type: 'object', additionalProperties: false,
  properties: {
    blocks: {
      type: 'array',
      items: {
        type: 'object', additionalProperties: false,
        properties: {
          q_number: { type: 'integer' },
          options: {
            type: 'array',
            items: {
              type: 'object', additionalProperties: false,
              properties: { label: { type: 'string', enum: ['A', 'B', 'C', 'D'] }, text: { type: 'string' } },
              required: ['label', 'text'],
            },
          },
          note: { type: 'string' },
        },
        required: ['q_number', 'options', 'note'],
      },
    },
  },
  required: ['blocks'],
}
function prompt(c) {
  return `Ты выравниваешь СТРУКТУРУ вариантов MCQ по разделу 99 контракта. Тема: ${A.topic}.

ЗАДАЧА: сделать так, чтобы правильный ответ НЕ ОТЛИЧАЛСЯ ОТ НЕПРАВИЛЬНЫХ ПО ВИДУ.
Сейчас его выдаёт форма: он длиннее, или устроен как перечисление, пока остальные —
однострочники. Смысл каждого варианта и то, какой из них верный, менять НЕЛЬЗЯ.

ЧИТАЙ ДВА ФАЙЛА:
1. \`${A.md_path}\` с offset=${c.off}, limit=${c.lim} — тела вопросов Q${c.lo}..Q${c.hi}.
   Каждое утверждение обязано остаться опровержимым/подтверждаемым по телу СВОЕГО Q.
2. \`${c.payload}\` — текущие варианты и список нарушенных осей по каждому блоку.
   Поле correct там указано: НЕ переставляй его на другой вариант.

ПРАВИЛА ПРАВКИ:
1. Держи у всех ЧЕТЫРЁХ одинаковыми: длину в символах (коридор 0.85–1.15 от
   правильного), ЧИСЛО ЧАСТЕЙ ФРАЗЫ (запятые + тире + точки с запятой — точное
   равенство), число код-спанов в обратных кавычках (разница не больше 1), число
   слов (0.77–1.30), финальную пунктуацию (у всех точка).
2. ДВА ЭТАПА, если правильный раздут: сначала СОКРАТИ его до одного утверждения
   (перечисление из трёх пунктов — сверни до главного признака), и только потом
   подгоняй остальные. Раздувать дистракторы под раздутый правильный ЗАПРЕЩЕНО:
   так дефект тиражируется.
3. Правильный ответ после сокращения обязан оставаться полным ответом на заголовок
   вопроса — не превращай его в намёк.
4. Дистрактор остаётся ложным ПО ТОЙ ЖЕ ОСИ и по-прежнему опровергается телом
   своего Q. Не подменяй ось, не делай его правдой, не тащи факты из соседних Q.
5. НЕ копируй зачин правильного в дистракторы — одинаковое начало это тоже подсказка.
5а. ЗАПАС ЗНАКОВ ОДИНАКОВ У ВСЕХ ЧЕТЫРЁХ. Двоеточие, точка с запятой, тире, цифра,
   отрицание, противопоставление («а», «но», «вместо») — если знак есть у правильного
   и ни у кого больше, это подсказка ровно того же рода, что и лишняя длина. Сворачивая
   перечисление, НЕ заменяй запятые двоеточием или точкой с запятой: получится
   единственный вариант с таким знаком. Проще всего держать все четыре в одной и той же
   пунктуационной форме.
6. Не своди абсолютные обороты («только», «всегда», «целиком», «никогда») в один
   вариант: если они есть у правильного и больше ни у кого — это подсказка.
7. Код-спаны в дистракторах — только те имена, что есть в теле своего Q.
8. СЛОВА СЧИТАЮТСЯ ДВУМЯ РАЗНЫМИ СПОСОБАМИ, держи запас по обоим. Один гейт режет
   текст по пробелам («по-прежнему», «HTTP-запросы» — одно слово), другой по границам
   слова (те же — два). Поэтому НЕ добирай длину дефисными словами: по первому счёту
   вариант останется коротким, и разброс max/min вылезет за 1.35. Добирай обычными
   отдельными словами.
9. Если вариант уже в норме — верни его текст без изменений.

Верни СТРОГО {"blocks":[...]} по тем блокам своего диапазона, КОТОРЫЕ ЕСТЬ В payload
(остальные уже в норме, их не трогай): q_number, четыре
опции с меткой и новым текстом, и note — одной фразой, что ты выровнял.`
}
phase('Repair')
const res = await parallel(A.chunks.map(c => () =>
  agent(prompt(c), { label: `fix:${c.label}`, phase: 'Repair', schema: SCHEMA })))
const blocks = res.filter(Boolean).flatMap(r => r.blocks || [])
log(`выровнено блоков: ${blocks.length}`)
return { count: blocks.length, q_numbers: blocks.map(b => b.q_number).sort((a, b) => a - b),
         chunks_ok: res.filter(Boolean).length, chunks_total: A.chunks.length }
